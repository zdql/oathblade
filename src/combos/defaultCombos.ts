export function buildCustomCombo(draft: CustomComboDraft, id?: string): ComboDefinition {
  const cleanSeq = draft.sequence.slice(0, 5);
  const preset = STYLE_PRESETS[draft.style] ?? STYLE_PRESETS.slash;
  const heavyCount = cleanSeq.filter((c) => c === 'J').length;
  const quickCount = cleanSeq.filter((c) => c === 'K').length;
  const startsWithCounter = cleanSeq[0] === 'L';

  const lengthScale = 1 + (cleanSeq.length - 2) * 0.28;
  const damageMultiplier = Number(
    (1.2 + heavyCount * 0.26 + quickCount * 0.14 + preset.dmgBonus * lengthScale).toFixed(2)
  );
  const poiseDamage = Math.round(18 + heavyCount * 12 + quickCount * 4 + preset.poiseBonus);
  const staminaCost = Math.min(34, Math.max(14, 10 + heavyCount * 6 + quickCount * 3));

  return {
    id: id ?? `custom_${Date.now()}_${Math.random().toString(36).slice(2, 6)}`,
    name: draft.name.trim() || 'Custom Technique',
    description: `Custom ${preset.label} forged from ${cleanSeq.join(' → ')}.`,
    sequence: cleanSeq,
    xpCost: 0,
    damageMultiplier,
    poiseDamage,
    staminaCost,
    lungeSpeed: preset.lunge,
    hitboxRadius: preset.radius,
    knockback: 210 + heavyCount * 35,
    guardBreak: preset.guardBreak || heavyCount >= 2,
    requiresCounterWindow: startsWithCounter,
    visualStyle: draft.style,
    accentColor: preset.color,
    isCustom: true,
  };
}
